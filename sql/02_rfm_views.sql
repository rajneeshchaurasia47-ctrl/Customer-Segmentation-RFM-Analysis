CREATE OR REPLACE VIEW VW_CUSTOMER_RFM_SEGMENTS AS
WITH BASE AS (
 SELECT CUSTOMER_ID, MAX(INVOICE_DATE) LAST_PURCHASE,
        COUNT(DISTINCT INVOICE_NO) FREQUENCY,
        SUM(QUANTITY*UNIT_PRICE) MONETARY,
        MAX(COUNTRY) KEEP (DENSE_RANK LAST ORDER BY INVOICE_DATE) COUNTRY
 FROM RFM_TRANSACTIONS
 WHERE CUSTOMER_ID IS NOT NULL AND QUANTITY>0 AND UNIT_PRICE>0
 GROUP BY CUSTOMER_ID
),
SNAP AS (SELECT TRUNC(MAX(INVOICE_DATE))+1 SNAPSHOT_DATE FROM RFM_TRANSACTIONS),
METRICS AS (
 SELECT B.*, S.SNAPSHOT_DATE, S.SNAPSHOT_DATE-TRUNC(B.LAST_PURCHASE) RECENCY
 FROM BASE B CROSS JOIN SNAP S
),
SCORED AS (
 SELECT M.*,
        6-NTILE(5) OVER (ORDER BY RECENCY ASC, CUSTOMER_ID) R_SCORE,
        NTILE(5) OVER (ORDER BY FREQUENCY ASC, CUSTOMER_ID) F_SCORE,
        NTILE(5) OVER (ORDER BY MONETARY ASC, CUSTOMER_ID) M_SCORE
 FROM METRICS M
),
SEGMENTED AS (
 SELECT S.*,
 CASE
  WHEN R_SCORE>=4 AND F_SCORE>=4 AND M_SCORE>=4 THEN 'Champions'
  WHEN R_SCORE>=3 AND F_SCORE>=4 THEN 'Loyal Customers'
  WHEN R_SCORE>=4 AND F_SCORE>=2 THEN 'Potential Loyalists'
  WHEN R_SCORE>=4 AND F_SCORE=1 THEN 'New Customers'
  WHEN R_SCORE<=2 AND F_SCORE>=3 THEN 'At Risk'
  WHEN R_SCORE<=2 AND F_SCORE<=2 THEN 'Hibernating'
  ELSE 'Needs Attention'
 END SEGMENT
 FROM SCORED S
)
SELECT CUSTOMER_ID,LAST_PURCHASE,FREQUENCY,MONETARY,COUNTRY,RECENCY,
       R_SCORE,F_SCORE,M_SCORE,
       TO_CHAR(R_SCORE)||TO_CHAR(F_SCORE)||TO_CHAR(M_SCORE) RFM_SCORE,
       SEGMENT,SNAPSHOT_DATE
FROM SEGMENTED;

CREATE OR REPLACE VIEW VW_RFM_SEGMENT_SUMMARY AS
SELECT SEGMENT, COUNT(*) CUSTOMERS, SUM(MONETARY) REVENUE,
       ROUND(AVG(MONETARY),2) AVG_CUSTOMER_VALUE,
       ROUND(AVG(RECENCY),1) AVG_RECENCY_DAYS,
       ROUND(100*COUNT(*)/SUM(COUNT(*)) OVER(),2) CUSTOMER_SHARE_PCT,
       ROUND(100*SUM(MONETARY)/SUM(SUM(MONETARY)) OVER(),2) REVENUE_SHARE_PCT
FROM VW_CUSTOMER_RFM_SEGMENTS GROUP BY SEGMENT;
