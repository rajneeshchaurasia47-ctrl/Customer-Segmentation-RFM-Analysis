CREATE TABLE RFM_TRANSACTIONS (
 INVOICE_NO VARCHAR2(20), STOCK_CODE VARCHAR2(30), DESCRIPTION VARCHAR2(300),
 QUANTITY NUMBER(12,2), INVOICE_DATE DATE, UNIT_PRICE NUMBER(12,4),
 CUSTOMER_ID NUMBER(12), COUNTRY VARCHAR2(100), REVENUE NUMBER(18,4)
);
CREATE INDEX IDX_RFM_TX_CUST ON RFM_TRANSACTIONS(CUSTOMER_ID);
CREATE INDEX IDX_RFM_TX_DATE ON RFM_TRANSACTIONS(INVOICE_DATE);

